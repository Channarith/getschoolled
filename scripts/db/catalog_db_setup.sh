#!/usr/bin/env bash
# First-boot setup for the catalog database VM (run by cloud-init as root; safe to re-run).
# Configures PostgreSQL 16 sized from this machine's RAM, TLS, private-network-only access,
# PgBouncer (optional listener), the firewall, and optional WAL archiving to object storage.
set -euo pipefail

# shellcheck disable=SC1091
source /etc/catalog-db/env
# shellcheck disable=SC1091
source /etc/catalog-db/secrets.env

PG_VERSION="$(ls /etc/postgresql | sort -V | tail -1)"
CONF_DIR="/etc/postgresql/${PG_VERSION}/main"
RAM_MB="$(awk '/MemTotal/ {printf "%d", $2/1024}' /proc/meminfo)"
CORES="$(nproc)"

SHARED_BUFFERS_MB=$(( RAM_MB / 4 ))
CACHE_MB=$(( RAM_MB * 60 / 100 ))
MAINT_MB=$(( RAM_MB / 16 )); [ "$MAINT_MB" -gt 1024 ] && MAINT_MB=1024

cat > "${CONF_DIR}/conf.d/10-catalog.conf" <<EOF
# Generated by catalog-db-setup for ${RAM_MB} MB RAM / ${CORES} cores. Edit and re-run to change.
listen_addresses = '*'
max_connections = 100
shared_buffers = ${SHARED_BUFFERS_MB}MB
effective_cache_size = ${CACHE_MB}MB
maintenance_work_mem = ${MAINT_MB}MB
work_mem = 16MB
random_page_cost = 1.1          # NVMe
effective_io_concurrency = 200
max_worker_processes = ${CORES}
max_parallel_workers = ${CORES}
max_parallel_workers_per_gather = 2
wal_compression = on
max_wal_size = 4GB
checkpoint_timeout = 15min
checkpoint_completion_target = 0.9
autovacuum_vacuum_scale_factor = 0.02
autovacuum_analyze_scale_factor = 0.01
autovacuum_max_workers = 3
log_min_duration_statement = 500
log_checkpoints = on
log_lock_waits = on
shared_preload_libraries = 'pg_stat_statements'
ssl = on
ssl_cert_file = '/etc/ssl/certs/ssl-cert-snakeoil.pem'
ssl_key_file = '/etc/ssl/private/ssl-cert-snakeoil.key'
password_encryption = scram-sha-256
EOF

# Only the private network (the VKE VPC) and the admin address may connect, always over TLS.
cat > "${CONF_DIR}/pg_hba.conf" <<EOF
local   all             postgres                                peer
local   all             all                                     scram-sha-256
hostssl ${CATALOG_DB_NAME} ${CATALOG_DB_USER} ${VPC_CIDR}       scram-sha-256
hostssl ${CATALOG_DB_NAME} ${CATALOG_DB_USER} ${ADMIN_CIDR}     scram-sha-256
EOF

if [ "${WAL_ARCHIVE:-0}" = "1" ]; then
  cat > /usr/local/bin/catalog-wal-push <<'EOS'
#!/usr/bin/env bash
set -euo pipefail
source /etc/catalog-db/env; source /etc/catalog-db/secrets.env
export RCLONE_CONFIG_VULTR_TYPE RCLONE_CONFIG_VULTR_PROVIDER RCLONE_CONFIG_VULTR_ENDPOINT \
       RCLONE_CONFIG_VULTR_ACCESS_KEY_ID RCLONE_CONFIG_VULTR_SECRET_ACCESS_KEY
rclone copyto --s3-no-check-bucket "$1" "vultr:${OBJECT_BUCKET}/${OBJECT_PREFIX}/wal/$2"
EOS
  chmod 0755 /usr/local/bin/catalog-wal-push
  cat >> "${CONF_DIR}/conf.d/10-catalog.conf" <<'EOF'
wal_level = replica
archive_mode = on
archive_command = '/usr/local/bin/catalog-wal-push %p %f'
archive_timeout = 300
EOF
fi

systemctl restart postgresql

# Database, role, extensions. The password never appears in a process list: it is read from the env file.
sudo -u postgres psql -v ON_ERROR_STOP=1 -v pw="${CATALOG_DB_PASSWORD}" <<EOF
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${CATALOG_DB_USER}') THEN
    CREATE ROLE ${CATALOG_DB_USER} LOGIN;
  END IF;
END \$\$;
ALTER ROLE ${CATALOG_DB_USER} PASSWORD :'pw';
SELECT 'CREATE DATABASE ${CATALOG_DB_NAME} OWNER ${CATALOG_DB_USER}'
  WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${CATALOG_DB_NAME}')\gexec
EOF
sudo -u postgres psql -v ON_ERROR_STOP=1 -d "${CATALOG_DB_NAME}" -c "CREATE EXTENSION IF NOT EXISTS pg_trgm; CREATE EXTENSION IF NOT EXISTS pg_stat_statements;"

# PgBouncer on 6432 (transaction pooling). The curriculum pool connects straight to 5432 until
# replicas x pool size approaches max_connections; switch CATALOG_DATABASE_URL to :6432 then.
cat > /etc/pgbouncer/pgbouncer.ini <<EOF
[databases]
${CATALOG_DB_NAME} = host=127.0.0.1 port=5432 dbname=${CATALOG_DB_NAME}
[pgbouncer]
listen_addr = *
listen_port = 6432
auth_type = scram-sha-256
auth_file = /etc/pgbouncer/userlist.txt
pool_mode = transaction
max_client_conn = 500
default_pool_size = 20
max_prepared_statements = 100
server_tls_sslmode = prefer
EOF
HASH="$(sudo -u postgres psql -Atc "SELECT rolpassword FROM pg_authid WHERE rolname='${CATALOG_DB_USER}'")"
printf '"%s" "%s"\n' "${CATALOG_DB_USER}" "${HASH}" > /etc/pgbouncer/userlist.txt
chown postgres:postgres /etc/pgbouncer/userlist.txt; chmod 0640 /etc/pgbouncer/userlist.txt
systemctl enable --now pgbouncer

# Firewall: private network and the admin address only. Nothing else listens publicly.
ufw --force reset >/dev/null
ufw default deny incoming
ufw default allow outgoing
ufw allow from "${ADMIN_CIDR}" to any port 22 proto tcp
ufw allow from "${VPC_CIDR}" to any port 5432 proto tcp
ufw allow from "${VPC_CIDR}" to any port 6432 proto tcp
ufw allow from "${ADMIN_CIDR}" to any port 5432 proto tcp
ufw --force enable

echo "catalog-db-setup finished: PostgreSQL ${PG_VERSION}, ${RAM_MB} MB RAM, WAL archive=${WAL_ARCHIVE:-0}"
