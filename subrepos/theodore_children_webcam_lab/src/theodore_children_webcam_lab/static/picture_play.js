// Coloring pages, numbered dots, and outlines for the vision-arcade picture games.
// Coordinates are fractions of the stage (origin top-left). Drawings are built
// on a square coloring sheet, then `at` places that sheet so the picture keeps
// its shape on the wide camera stage.

function at(px, py) {
  const height = 0.64;
  const width = height / 1.85;
  const x0 = (1 - width) / 2;
  return [x0 + px * width, 0.085 + py * height];
}

// Closed cardinal spline through control points. The first sample is the first
// control, so callers can keep that point inside the page.
function contour(controls, samples = 4, tension = 0.34) {
  const count = controls.length;
  if (count < 3) return controls.map((point) => [point[0], point[1]]);
  const pull = (1 - tension) / 2;
  const points = [];
  for (let i = 0; i < count; i += 1) {
    const p0 = controls[(i - 1 + count) % count];
    const p1 = controls[i];
    const p2 = controls[(i + 1) % count];
    const p3 = controls[(i + 2) % count];
    for (let step = 0; step < samples; step += 1) {
      const t = step / samples;
      const t2 = t * t;
      const t3 = t2 * t;
      const h1 = 2 * t3 - 3 * t2 + 1;
      const h2 = -2 * t3 + 3 * t2;
      const h3 = t3 - 2 * t2 + t;
      const h4 = t3 - t2;
      points.push([
        h1 * p1[0] + h2 * p2[0] + h3 * pull * (p2[0] - p0[0]) + h4 * pull * (p3[0] - p1[0]),
        h1 * p1[1] + h2 * p2[1] + h3 * pull * (p2[1] - p0[1]) + h4 * pull * (p3[1] - p1[1]),
      ]);
    }
  }
  return points;
}

function shape(pagePoints, samples = 4, tension = 0.34) {
  return contour(pagePoints.map(([x, y]) => at(x, y)), samples, tension);
}

function ribbon(controls, width, samples = 4, tension = 0.28) {
  const count = controls.length;
  if (count < 2) return controls.map((point) => [point[0], point[1]]);
  const pull = (1 - tension) / 2;
  const center = [];
  for (let i = 0; i < count - 1; i += 1) {
    const p0 = controls[Math.max(0, i - 1)];
    const p1 = controls[i];
    const p2 = controls[i + 1];
    const p3 = controls[Math.min(count - 1, i + 2)];
    for (let step = 0; step < samples; step += 1) {
      const t = step / samples;
      const t2 = t * t;
      const t3 = t2 * t;
      const h1 = 2 * t3 - 3 * t2 + 1;
      const h2 = -2 * t3 + 3 * t2;
      const h3 = t3 - 2 * t2 + t;
      const h4 = t3 - t2;
      center.push([
        h1 * p1[0] + h2 * p2[0] + h3 * pull * (p2[0] - p0[0]) + h4 * pull * (p3[0] - p1[0]),
        h1 * p1[1] + h2 * p2[1] + h3 * pull * (p2[1] - p0[1]) + h4 * pull * (p3[1] - p1[1]),
      ]);
    }
  }
  center.push(controls[count - 1]);
  const left = [];
  const right = [];
  for (let i = 0; i < center.length; i += 1) {
    const prev = center[Math.max(0, i - 1)];
    const next = center[Math.min(center.length - 1, i + 1)];
    let dx = next[0] - prev[0];
    let dy = next[1] - prev[1];
    const mag = Math.hypot(dx, dy) || 1;
    dx /= mag;
    dy /= mag;
    left.push([center[i][0] - dy * width, center[i][1] + dx * width]);
    right.push([center[i][0] + dy * width, center[i][1] - dx * width]);
  }
  return left.concat(right.reverse());
}

function band(pagePoints, pageWidth, samples = 4) {
  return ribbon(pagePoints.map(([x, y]) => at(x, y)), pageWidth * (0.64 / 1.85), samples, 0.3);
}

function blob(cx, cy, rx, ry, spin = 0, bump = 0.14) {
  const controls = [];
  for (let i = 0; i < 8; i += 1) {
    const turn = spin + (i / 8) * Math.PI * 2;
    const wave = 1 + bump * Math.sin(turn * 2 + spin * 4);
    controls.push([cx + Math.cos(turn) * rx * wave, cy + Math.sin(turn) * ry * wave]);
  }
  return shape(controls, 3, 0.22);
}

function part(name, colorName, color, points) {
  return { name, colorName, color, points };
}

function picture(word, segments, outline) {
  return { word, segments, outline: outline || segments[0].points };
}

