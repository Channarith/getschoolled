def main() -> int:
    lines: dict[str, dict[str, str]] = {}
    for english, row in ROWS.items():
        if len(row) != len(LANGS):
            raise SystemExit(f"{english!r} has {len(row)} langs, need {len(LANGS)}")
        lines[normalize(english)] = dict(zip(LANGS, row))
    dest = ROOT / "data" / "i18n_packs" / "en-be-your-spiderman-audio-v1.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        json.dumps(
            {
                "song_id": "en-be-your-spiderman-audio-v1",
                "languages": list(LANGS),
                "lines": lines,
            },
            ensure_ascii=False,
            indent=1,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {dest} ({len(lines)} unique lines x {len(LANGS)} languages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
