/**
 * Ensure react-native has minimal web shims for Expo web bundling.
 *
 * Do NOT re-export *.ios.js as *.web.js — that pulls BatchedBridge /
 * NativeModules into the web graph and crashes with:
 *   Invariant Violation: __fbBatchedBridgeConfig is not set
 *
 * Only write:
 *   - Platform.web.js → react-native-web Platform
 *   - legacySendAccessibilityEvent.web.js → no-op stub
 * And delete any leftover ios→web shims from older patch runs.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const RN_ROOT = path.join(ROOT, "node_modules", "react-native");

const KEEP = new Set([
  path.join("Libraries", "Utilities", "Platform.web.js"),
  path.join(
    "Libraries",
    "Components",
    "AccessibilityInfo",
    "legacySendAccessibilityEvent.web.js",
  ),
]);

const SPECIAL = [
  {
    rel: path.join("Libraries", "Utilities", "Platform.web.js"),
    contents: `/**
 * Auto-generated by scripts/patch-react-native-platform-web.js — do not edit.
 */
module.exports = require("react-native-web/dist/exports/Platform");
`,
  },
  {
    rel: path.join(
      "Libraries",
      "Components",
      "AccessibilityInfo",
      "legacySendAccessibilityEvent.web.js",
    ),
    contents: `/**
 * Auto-generated by scripts/patch-react-native-platform-web.js — do not edit.
 */
module.exports = function legacySendAccessibilityEvent() {};
`,
  },
];

function walkDeleteIosWebShims() {
  let removed = 0;
  const stack = [RN_ROOT];
  while (stack.length) {
    const dir = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        if (
          ent.name === "ReactAndroid" ||
          ent.name === "ReactCommon" ||
          ent.name === "__tests__" ||
          ent.name === "tests"
        ) {
          continue;
        }
        stack.push(full);
        continue;
      }
      if (!ent.name.endsWith(".web.js")) continue;
      const rel = path.relative(RN_ROOT, full);
      if (KEEP.has(rel)) continue;
      let text = "";
      try {
        text = fs.readFileSync(full, "utf8");
      } catch {
        continue;
      }
      // Only remove shims we (or the old patch) generated that re-export ios.
      if (
        text.includes("Auto web shim → ios") ||
        /module\.exports\s*=\s*require\(["']\.\/[^"']+\.ios\.js["']\)/.test(text)
      ) {
        fs.unlinkSync(full);
        removed += 1;
      }
    }
  }
  return removed;
}

function main() {
  const rnWeb = path.join(ROOT, "node_modules", "react-native-web");
  if (!fs.existsSync(rnWeb) || !fs.existsSync(RN_ROOT)) {
    console.warn("patch-react-native-platform-web: rn/rn-web missing; skip");
    return;
  }
  for (const { rel, contents } of SPECIAL) {
    const target = path.join(RN_ROOT, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, contents);
    console.log("patch-react-native-platform-web: wrote", rel);
  }
  const n = walkDeleteIosWebShims();
  console.log(`patch-react-native-platform-web: removed ${n} ios→web shim(s)`);
}

main();
