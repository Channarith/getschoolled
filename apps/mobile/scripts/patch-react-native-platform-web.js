/**
 * Ensure react-native has web shims for platform-only modules Expo web needs.
 * RN 0.74 ships several files as *.ios.js / *.android.js only; without a .web
 * (or plain .js) file, relative imports inside react-native 500 the web bundle.
 *
 * Strategy:
 *  1. Prefer react-native-web for Platform.
 *  2. Stub a11y helper that has no web meaning.
 *  3. For any remaining *.ios.js with no *.web.js / *.js sibling, re-export the
 *     ios variant so Metro web can resolve the module.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const RN_ROOT = path.join(ROOT, "node_modules", "react-native");

const SPECIAL = [
  {
    rel: path.join(
      "Libraries",
      "Utilities",
      "Platform.web.js",
    ),
    contents: `/**
 * Auto-generated by scripts/patch-react-native-platform-web.js — do not edit.
 */
module.exports = require("react-native-web/dist/exports/Platform");
`,
  },
  {
    rel: path.join(
      "Libraries",
      "Components",
      "AccessibilityInfo",
      "legacySendAccessibilityEvent.web.js",
    ),
    contents: `/**
 * Auto-generated by scripts/patch-react-native-platform-web.js — do not edit.
 */
module.exports = function legacySendAccessibilityEvent() {};
`,
  },
];

function walkIosShims() {
  let created = 0;
  const stack = [RN_ROOT];
  while (stack.length) {
    const dir = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        if (
          ent.name === "ReactAndroid" ||
          ent.name === "ReactCommon" ||
          ent.name === "__tests__" ||
          ent.name === "tests"
        ) {
          continue;
        }
        stack.push(full);
        continue;
      }
      if (!ent.name.endsWith(".ios.js")) continue;
      const base = ent.name.slice(0, -".ios.js".length);
      const web = path.join(dir, `${base}.web.js`);
      const plain = path.join(dir, `${base}.js`);
      if (fs.existsSync(web) || fs.existsSync(plain)) continue;
      fs.writeFileSync(
        web,
        `/** Auto web shim → ios variant (patch-react-native-platform-web.js) */\n` +
          `module.exports = require("./${base}.ios.js");\n`,
      );
      created += 1;
    }
  }
  return created;
}

function main() {
  const rnWeb = path.join(ROOT, "node_modules", "react-native-web");
  if (!fs.existsSync(rnWeb) || !fs.existsSync(RN_ROOT)) {
    console.warn("patch-react-native-platform-web: rn/rn-web missing; skip");
    return;
  }
  for (const { rel, contents } of SPECIAL) {
    const target = path.join(RN_ROOT, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, contents);
    console.log("patch-react-native-platform-web: wrote", rel);
  }
  const n = walkIosShims();
  console.log(`patch-react-native-platform-web: created ${n} ios→web shims`);
}

main();
